import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFile,mkdir,stat} from 'node:fs/promises';
import {resolve,extname} from 'node:path';
import {chromium} from 'playwright';
const root=resolve('dist'),evidence=resolve('test-results/catalogue');
await mkdir(evidence,{recursive:true});
const headers=await readFile('web/_headers','utf8');
const csp=headers.match(/Content-Security-Policy: (.+)/)[1];
const server=createServer(async(req,res)=>{
 try {
  let pathname=new URL(req.url,'http://localhost').pathname;
  let file=resolve(root,'.'+pathname);if(!file.startsWith(root+'/')&&file!==root)throw Error('path');
  if((await stat(file)).isDirectory())file=resolve(file,'index.html');
  const bytes=await readFile(file);
  res.setHeader('Content-Security-Policy',csp);
  res.setHeader('Content-Type',({'.html':'text/html','.js':'text/javascript','.css':'text/css','.json':'application/json','.png':'image/png','.jpg':'image/jpeg','.webp':'image/webp','.ttf':'font/ttf','.xml':'application/xml'})[extname(file)]||'application/octet-stream');res.end(bytes);
 }catch {res.writeHead(404);res.end('Not found');}
});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const origin='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({headless:true,channel:process.env.CHROMIUM_CHANNEL||'chrome'});
const snapshot=JSON.parse(await readFile('data/series.json','utf8'));
const solo=snapshot.series.find(s=>s.id===105398);
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000},serviceWorkers:'block'});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error'&&/Content Security Policy|Refused to/.test(m.text()))errors.push(m.text());});
 await page.goto(origin+'/manga/');
 assert.equal(await page.locator('.series-card').count(),snapshot.series.length);
 await page.getByRole('searchbox').fill('Na Honjaman Level Up');
 await page.waitForFunction(()=>document.querySelector('#search-status').textContent.includes('matches for'));
 assert.equal(await page.locator('.series-card').first().getAttribute('data-series-id'),'105398');
 await page.locator('.series-card').first().getByRole('link').click();
 await page.getByRole('heading',{level:1,name:'Solo Leveling',exact:true}).waitFor();
 assert.equal(new URL(page.url()).pathname,solo.path);
 assert.equal(await page.locator('.hero-cover img').evaluate(i=>i.complete&&i.naturalWidth>0),true);
 assert.equal(await page.getByRole('link',{name:'Open in Nyora'}).getAttribute('href'),'/#/search?q=Solo%20Leveling');
 assert.equal(await page.locator('.related .series-card').count(),4);
 await page.screenshot({path:resolve(evidence,'solo-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.waitForTimeout(150);
 await page.screenshot({path:resolve(evidence,'solo-mobile.png')});
 await page.goto(origin+'/manga/');
 await page.getByRole('searchbox').fill('zzzzunknown987');
 await page.locator('#search-empty').waitFor({state:'visible'});
 assert.equal(await page.locator('.series-card').count(),0);
 await page.getByRole('searchbox').fill('');
 await page.waitForFunction(n=>document.querySelectorAll('.series-card').length===n,snapshot.series.length);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:resolve(evidence,'catalogue-mobile.png'),fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:resolve(evidence,'catalogue-desktop.png'),fullPage:true});
 await page.route('**/manga/search-index.json',r=>r.abort());
 await page.reload();await page.getByRole('searchbox').fill('Solo');
 await page.waitForFunction(()=>document.querySelector('#search-status').textContent.includes('unavailable'));
 assert.equal(await page.locator('.series-card').count(),snapshot.series.length);
 const plain=await browser.newContext({javaScriptEnabled:false});
 const crawler=await plain.newPage();
 await crawler.goto(origin+'/manga/');
 assert.equal(await crawler.locator('.series-card a').count(),snapshot.series.length);
 await crawler.goto(origin+solo.path);
 assert.equal(await crawler.locator('h1').textContent(),'Solo Leveling');
 assert((await crawler.locator('.synopsis').textContent()).length>100);
 assert.equal(await crawler.locator('link[rel=canonical]').getAttribute('href'),'https://web.nyora.xyz'+solo.path);
 assert.equal((await crawler.goto(origin+'/manga/nonexistent/')).status(),404);
 await plain.close();assert.deepEqual(errors,[]);
 console.log('Catalogue: TF-IDF alias search, related links, covers, mobile layout, no-JS content, strict CSP and error fallback passed.');
}finally{await browser.close();await new Promise(r=>server.close(r));}
