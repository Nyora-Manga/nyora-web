// Writes web/core/cloudflare-sources.js: the catalogue sources that sit behind
// a Cloudflare wall. The web app cannot pass those challenges (only the desktop
// app's embedded browser can), so they are hidden on web.
//
// Source of truth is the catalogue the desktop app ships. Deploys refresh it;
// if the fetch fails the committed list stays in place.
import { readFile, writeFile } from 'node:fs/promises';

const URL_ = 'https://raw.githubusercontent.com/Nyora-Manga/nyora-desktop/main/vendor/helper/data/catalogue.json';
const out = new URL('../web/core/cloudflare-sources.js', import.meta.url);

// Same rule as the desktop catalogue smoke test.
export const behindCloudflare = (s) => String(s.antiBot).toLowerCase() === 'cloudflare' || /^[AB]$/i.test(s.cfWall || '');

async function catalogue() {
  const local = process.argv[2];
  if (local) return JSON.parse(await readFile(local, 'utf8'));
  const res = await fetch(URL_, { signal: AbortSignal.timeout(30_000) });
  if (!res.ok) throw new Error(`catalogue fetch failed (${res.status})`);
  return res.json();
}

try {
  const { sources } = await catalogue();
  if (!Array.isArray(sources) || sources.length < 100) throw new Error('catalogue looks truncated');
  // Lowercase: the catalogue spells some IDs in capitals, the helper does not.
  const ids = [...new Set(sources.filter(behindCloudflare).map((s) => `data:${String(s.id).toLowerCase()}`))].sort();
  await writeFile(out, '// Generated by scripts/refresh-cloudflare-sources.mjs — do not edit.\n'
    + '// Catalogue sources behind Cloudflare; the web app hides them (desktop keeps them).\n'
    + `export const CLOUDFLARE_SOURCES = new Set(${JSON.stringify(ids, null, 1).replace(/\n /g, '\n  ')});\n`);
  console.log(`Cloudflare sources hidden on web: ${ids.length} of ${sources.length}`);
} catch (error) {
  console.warn(`Keeping the committed Cloudflare source list: ${error.message}`);
}
